"""Generate bundled French recordings with macOS say/afconvert.

Requires the local site on port 4173 and the dedicated Chrome test profile on
port 9223, like tests/browser_check.py. No personal browser data is accessed.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor, as_completed
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import subprocess
import tempfile
import time
import unicodedata

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'assets/audio/fr'
MANIFEST = ROOT / 'js/audio-manifest.js'


def collect_texts():
    spec = importlib.util.spec_from_file_location('habibi_browser', ROOT / 'tests/browser_check.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    browser = module.Browser()
    try:
        browser.navigate('http://127.0.0.1:4173/?audio-catalog=' + str(time.time_ns()))
        browser.wait("!!document.querySelector('.theme-card')")
        return browser.js("""(async()=>{
          const {baseLessons,conjugations,makeBaseQuestions}=await import('./js/content.js');
          const published=await (await fetch('./data/custom-lessons.json',{cache:'no-store'})).json();
          const texts=new Set();
          const add=value=>{if(typeof value==='string'&&value.trim())texts.add(value.normalize('NFC').replace(/\\s+/g,' ').trim())};
          for(const lesson of [...baseLessons,...published.lessons]) {
            for(const card of lesson.cards){add(card.fr);add(card.example?.fr)}
          }
          for(const row of conjugations){add(row.etre.fr);add(row.avoir.fr)}
          add('être');add('avoir');
          const groups=[...Object.values(makeBaseQuestions()),...published.lessons];
          for(const group of groups)for(const mode of ['quiz','exercises'])for(const q of group[mode]||[]) {
            add(q.audio);add(q.sentence||q.audio||q.correct);
            if(mode==='exercises')for(const option of q.options)add(q.prompt.split('. ')[0].replace('…',option.text).replace('J’ ai','J’ai'));
          }
          return [...texts].sort();
        })()""")
    finally:
        browser.sock.close()


def valid_recording(path):
    if not path.is_file() or path.stat().st_size < 4500:
        return False
    result = subprocess.run(['afinfo', str(path)], text=True, capture_output=True)
    match = re.search(r'estimated duration:\s*([0-9.]+)', result.stdout)
    return result.returncode == 0 and match is not None and float(match.group(1)) > 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--voice', default='Thomas')
    parser.add_argument('--rate', type=int, default=150)
    parser.add_argument('--workers', type=int, default=3)
    args = parser.parse_args()
    texts = sorted({unicodedata.normalize('NFC', re.sub(r'\s+', ' ', value)).strip() for value in collect_texts()})
    if not texts:
        raise SystemExit('No French audio texts found')
    OUTPUT.mkdir(parents=True, exist_ok=True)

    def generate(text):
        filename = hashlib.sha256(text.encode('utf-8')).hexdigest()[:20] + '.m4a'
        target = OUTPUT / filename
        if not valid_recording(target):
            with tempfile.TemporaryDirectory(prefix='habibi-fr-') as temp:
                source = Path(temp) / 'speech.aiff'
                subprocess.run(['say', '-v', args.voice, '-r', str(args.rate), '-o', str(source), text], check=True, capture_output=True)
                subprocess.run(['afconvert', '-f', 'm4af', '-d', 'aac ', '-b', '48000', str(source), str(target)], check=True, capture_output=True)
            if not valid_recording(target):
                raise RuntimeError('Empty or invalid recording: ' + text)
        return text, filename

    recordings = {}
    print('Preparing ' + str(len(texts)) + ' French recordings', flush=True)
    with ThreadPoolExecutor(max_workers=args.workers) as executor:
        for future in as_completed([executor.submit(generate, value) for value in texts]):
            text, filename = future.result()
            recordings[text] = filename
            if len(recordings) % 20 == 0 or len(recordings) == len(texts):
                print(str(len(recordings)) + '/' + str(len(texts)) + ' recordings ready', flush=True)
    ordered = dict(sorted(recordings.items()))
    MANIFEST.write_text('// Generated by scripts/generate_audio.py; French voice ' + args.voice + '.\nexport const recordedAudio = Object.freeze(' + json.dumps(ordered, ensure_ascii=False, indent=2) + ');\n')
    size = sum((OUTPUT / filename).stat().st_size for filename in recordings.values())
    print(json.dumps({'recordings': len(recordings), 'bytes': size, 'manifest': str(MANIFEST)}), flush=True)


if __name__ == '__main__':
    main()
